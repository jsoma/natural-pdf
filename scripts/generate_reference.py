def _import_engine_provider_modules() -> None:
    """Import the modules that register built-in engines at import time.

    All registrations are metadata-only (factories are lazy), so this never
    loads models or touches the network.
    """
    import importlib

    for module in (
        "natural_pdf",
        "natural_pdf.classification.classification_provider",
        "natural_pdf.checkbox.checkbox_manager",
        "natural_pdf.deskew.deskew_provider",
        "natural_pdf.guides.guides_provider",
        "natural_pdf.layout.layout_manager",
        "natural_pdf.ocr.ocr_provider",
        "natural_pdf.selectors.selector_provider",
        "natural_pdf.tables.structure_provider",
        "natural_pdf.tables.table_provider",
    ):
        importlib.import_module(module)


def _manager_specs() -> Dict[str, Any]:
    """Return EngineManagerSpec objects keyed by capability, where available."""
    import importlib

    specs: Dict[str, Any] = {}
    for module_name in (
        "natural_pdf.layout.layout_manager",
        "natural_pdf.checkbox.checkbox_manager",
    ):
        module = importlib.import_module(module_name)
        spec = getattr(module, "_MANAGER", None)
        if spec is not None:
            specs[spec.capability] = spec
    return specs


def _optional_dep_hint_for(install_hint: Optional[str]) -> Optional[str]:
    """Expand a bare pip hint to the optional_imports hints when they match."""
    if not install_hint:
        return None
    from natural_pdf.utils.optional_imports import OPTIONAL_DEPENDENCIES

    for dep in OPTIONAL_DEPENDENCIES.values():
        if install_hint in dep.install_hints:
            return " or ".join(dep.install_hints)
    return install_hint


def generate_engines_page() -> str:
    _import_engine_provider_modules()

    from natural_pdf.engine_provider import get_provider
    from natural_pdf.engine_registry import list_engines
    from natural_pdf.ocr import unified_dispatch

    provider = get_provider()
    specs = _manager_specs()
    unified = unified_dispatch.list_engines()

    all_engines = list_engines()

    def rows_for(capability: str) -> List[Tuple[str, str, str]]:
        spec = specs.get(capability)
        rows = []
        for name in sorted(all_engines.get(capability, ())):
            metadata = provider.get_metadata(capability, name) or {}
            notes: List[str] = []

            if spec is not None and name in spec.deprecated_aliases:
                notes.append(f"deprecated alias for `{spec.deprecated_aliases[name]}`")
            options_class = metadata.get("options_class")
            if options_class is not None and options_class is not type(None):
                notes.append(f"options: `{options_class.__name__}`")
            for key in sorted(metadata):
                if key in {"options_class", "class_factory", "install_hint"}:
                    continue
                value = metadata[key]
                if isinstance(value, (str, int, float, bool)):
                    notes.append(f"{key}: {value}")

            install = None
            if capability.startswith("ocr") and name in unified:
                install = unified[name].install_hint
            if install is None and spec is not None:
                install = spec.install_hints.get(name)
            if install is None:
                install = metadata.get("install_hint")
            install = _optional_dep_hint_for(install)

            rows.append((_code(name), install or "included", "; ".join(notes) or ""))
        return rows

    # Group capabilities that expose identical engine tables (e.g. the ocr trio).
    by_rows: Dict[Tuple[Tuple[str, str, str], ...], List[str]] = {}
    for capability in sorted(all_engines):
        key = tuple(rows_for(capability))
        by_rows.setdefault(key, []).append(capability)

    sections: List[str] = []
    for rows, capabilities in sorted(by_rows.items(), key=lambda item: item[1][0]):
        title = _code(capabilities[0])
        if len(capabilities) > 1:
            title += " (also " + ", ".join(_code(c) for c in capabilities[1:]) + ")"
        sections.append(f"## Capability: {title}")
        sections.append(_md_table(["Engine", "Requires", "Notes"], rows))

    # Unified OCR dispatch registry (includes VLM shorthands not registered
    # as provider engines).
    sections.append("## OCR dispatch registry")
    sections.append(
        "The unified OCR registry behind `page.apply_ocr(engine=...)`. Named VLM-family "
        "entries resolve to local vision-language models instead of classic OCR engines; "
        "the generic `vlm` entry can use either a local model or a configured remote client."
    )
    ocr_rows = []
    for name in sorted(unified):
        entry = unified[name]
        details: List[str] = []
        if entry.vlm_family:
            details.append(f"VLM family: {entry.vlm_family}")
        if entry.options_class is not None:
            details.append(f"options: `{entry.options_class.__name__}`")
        install = _optional_dep_hint_for(entry.install_hint)
        ocr_rows.append(
            (_code(name), entry.engine_type, install or "included", "; ".join(details) or "")
        )
    sections.append(_md_table(["Engine", "Type", "Requires", "Notes"], ocr_rows))

    intro = (
        "Engines registered per capability in the engine registry "
        '(`natural_pdf.engine_registry.list_engines`). "Requires" shows the install '
        'hint carried by the registration metadata; "included" means the '
        "registration declares no extra install requirement (availability may still "
        "depend on optional packages — run `npdf doctor` to check your environment).\n\n"
        "This page lists the built-in engines only. Third-party plugins registered "
        "through the `natural_pdf.engines` entry point extend these lists at runtime "
        "in your environment; they are deliberately not part of the generated "
        "reference."
    )
    return _page("Engine Reference", intro, "\n\n".join(sections))


