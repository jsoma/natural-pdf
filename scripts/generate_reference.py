def build_all_pages() -> Dict[str, str]:
    """Introspect the registries in THIS process and render every page.

    Only safe when the current interpreter is pristine (nothing has mutated
    the global registries). ``main()`` never calls this directly for output —
    it goes through :func:`build_all_pages_isolated` instead.
    """
    return {name: generator() for name, generator in sorted(PAGES.items())}


ENGINE_ENTRY_POINT_GROUP = "natural_pdf.engines"  # EngineProvider.ENTRY_POINT_GROUP


def _suppress_engine_entry_point_plugins() -> None:
    """Hide third-party ``natural_pdf.engines`` plugins from introspection.

    Policy: the generated reference documents built-in engines only, so the
    drift gate cannot flap depending on which plugins happen to be installed.
    ``EngineProvider._ensure_entry_points_loaded`` runs unconditionally at
    ``natural_pdf.engine_provider`` import time and has no opt-out flag, so
    this must patch ``importlib.metadata.entry_points`` BEFORE natural_pdf is
    imported. Only meaningful in the ``--introspect-json`` subprocess, which
    starts from a clean interpreter.
    """
    import importlib.metadata as importlib_metadata

    real_entry_points = importlib_metadata.entry_points

    class _FilteredEntryPoints:
        """Proxy that empties the engine plugin group for both lookup styles."""

        def __init__(self, wrapped: Any) -> None:
            self._wrapped = wrapped

        def select(self, **params: Any) -> Any:  # importlib.metadata >= 3.10
            if params.get("group") == ENGINE_ENTRY_POINT_GROUP:
                return ()
            return self._wrapped.select(**params)

        def get(self, group: str, default: Any = None) -> Any:  # legacy mapping API
            if group == ENGINE_ENTRY_POINT_GROUP:
                return () if default is None else default
            getter = getattr(self._wrapped, "get", None)
            return getter(group, default) if callable(getter) else default

        def __iter__(self) -> Any:
            return iter(self._wrapped)

        def __getattr__(self, name: str) -> Any:
            return getattr(self._wrapped, name)

    def filtered_entry_points(**params: Any) -> Any:
        if params.get("group") == ENGINE_ENTRY_POINT_GROUP:
            return ()
        return _FilteredEntryPoints(real_entry_points(**params))

    importlib_metadata.entry_points = filtered_entry_points


def build_all_pages_isolated() -> Dict[str, str]:
    """Run all registry introspection in a fresh interpreter and return pages.

    The registries this script reads (selector clauses, engine provider,
    unified OCR dispatch) are mutable process globals: test suites register
    throwaway engines, and installed plugins self-register on import. A fresh
    ``sys.executable`` subprocess (``--introspect-json``) guarantees the pages
    reflect a clean ``import natural_pdf`` regardless of what already ran in
    the calling process.
    """
    with tempfile.TemporaryDirectory() as tmp:
        out_path = Path(tmp) / "pages.json"
        try:
            proc = subprocess.run(
                [
                    sys.executable,
                    str(Path(__file__).resolve()),
                    "--introspect-json",
                    str(out_path),
                ],
                cwd=REPO_ROOT,
                capture_output=True,
                text=True,
                timeout=INTROSPECTION_TIMEOUT_SECONDS,
            )
        except subprocess.TimeoutExpired as exc:
            raise ReferenceGenerationError(
                "introspection subprocess timed out after "
                f"{INTROSPECTION_TIMEOUT_SECONDS} seconds"
            ) from exc
        if proc.returncode != 0:
            raise ReferenceGenerationError(
                "introspection subprocess failed:\n" + (proc.stderr.strip() or proc.stdout.strip())
            )
        pages = json.loads(out_path.read_text(encoding="utf-8"))
    if sorted(pages) != sorted(PAGES):
        raise ReferenceGenerationError(
            f"introspection subprocess returned pages {sorted(pages)}, " f"expected {sorted(PAGES)}"
        )
    return pages


def find_orphaned_pages(output_dir: Path, expected_names: Iterable[str]) -> List[Path]:
    """Markdown files in ``output_dir`` that carry the GENERATED header but are
    no longer in the expected page set — leftovers from pages this script used
    to generate. Hand-written pages (no header) are never returned: the header
    namespace belongs to this generator, everything else is off limits."""
    expected = set(expected_names)
    orphans: List[Path] = []
    if not output_dir.is_dir():
        return orphans
    for path in sorted(output_dir.glob("*.md")):
        if path.name in expected:
            continue
        try:
            content = path.read_text(encoding="utf-8")
        except OSError:
            continue
        if content.startswith(HEADER_COMMENT):
            orphans.append(path)
    return orphans


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help=(
            "Regenerate in memory and exit nonzero if the committed pages "
            "differ or an orphaned generated page lingers in the output dir."
        ),
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help=f"Output directory (default: {DEFAULT_OUTPUT_DIR})",
    )
    parser.add_argument(
        "--introspect-json",
        type=Path,
        metavar="PATH",
        help=(
            "Internal: introspect the registries in this (clean) interpreter, "
            "write {page: markdown} JSON to PATH, and exit. Suppresses "
            "third-party engine entry-point plugins."
        ),
    )
    args = parser.parse_args(argv)

    if args.introspect_json is not None:
        _suppress_engine_entry_point_plugins()
        pages = build_all_pages()
        args.introspect_json.write_text(json.dumps(pages), encoding="utf-8")
        return 0

    pages = build_all_pages_isolated()

    if args.check:
        stale: List[str] = []
        for name, content in pages.items():
            path = args.output / name
            if not path.exists():
                stale.append(f"{path}: missing")
            elif path.read_text(encoding="utf-8") != content:
                stale.append(f"{path}: out of date")
        for orphan in find_orphaned_pages(args.output, pages):
            stale.append(
                f"{orphan}: orphaned generated page (bears the GENERATED header "
                "but is no longer generated)"
            )
        if stale:
            for line in stale:
                print(line, file=sys.stderr)
            print(
                "Reference pages are out of date. Regenerate with: "
                "uv run python scripts/generate_reference.py",
                file=sys.stderr,
            )
            return 1
        print(f"{len(pages)} reference pages up to date in {args.output}")
        return 0

    args.output.mkdir(parents=True, exist_ok=True)
    for name, content in pages.items():
        path = args.output / name
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path} ({len(content.splitlines())} lines)")
    # Generation owns the GENERATED-header namespace: pages this script no
    # longer produces are deleted so they cannot linger on the site forever.
    for orphan in find_orphaned_pages(args.output, pages):
        orphan.unlink()
        print(f"removed orphaned generated page {orphan}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
