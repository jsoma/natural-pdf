#!/usr/bin/env python
"""Generate markdown reference pages under docs/reference/ from library introspection.

Usage:
    uv run python scripts/generate_reference.py            # write pages
    uv run python scripts/generate_reference.py --check    # CI drift gate

The pages are regenerated from the library's own registries and typed
structures so they cannot drift from the code:

- selectors.md            selector vocabulary (pseudo-classes, attribute operators)
- engines.md              engines per capability from the engine registry
- installation-extras.md  optional dependency groups from utils.optional_imports
- exceptions.md           exception hierarchy from natural_pdf.exceptions
- ocr-options.md          per-engine OCR option tables from ocr.ocr_options

Descriptions the registries do not carry are curated in the maps below. The
generator fails loudly when a registered name has no curated description (or a
curated name is no longer registered) — that is the drift guard. Every curated
example selector must also parse via ``natural_pdf.selectors.parser``.

Isolation: the registries this script introspects are mutable process globals
(selector clauses, the engine provider, the unified OCR dispatch table).
Anything imported earlier in the same interpreter — a test suite that registers
throwaway engines, a third-party package that self-registers on import — would
otherwise leak into the output. ``main()`` therefore never introspects in the
current process: it re-invokes this script with ``--introspect-json`` in a
fresh subprocess and uses what a clean ``import natural_pdf`` sees.

Third-party plugin policy: the generated pages document BUILT-IN registrations
only. The introspection subprocess filters the ``natural_pdf.engines``
entry-point group before importing the library, so installed plugins never
appear (and cannot make the CI drift gate flap across environments). The
affected pages say so in their intro text.
"""

