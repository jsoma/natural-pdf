def _guard_registry_coverage(
    registry_names: Iterable[str],
    curated: Mapping[str, Tuple[str, str]],
    aliases: Mapping[str, Tuple[str, ...]],
    kind: str,
) -> None:
    """Fail loudly when the live registry and curated maps disagree."""
    registered = set(registry_names)
    alias_names = {alias for names in aliases.values() for alias in names}
    covered = set(curated) | alias_names

    missing = sorted(registered - covered)
    if missing:
        raise ReferenceGenerationError(
            f"{kind}: registered names missing a curated description in "
            f"scripts/generate_reference.py: {missing}. Add them to the curated map."
        )
    stale = sorted(set(curated) - registered)
    if stale:
        raise ReferenceGenerationError(
            f"{kind}: curated descriptions for names that are no longer registered: {stale}. "
            "Remove them from scripts/generate_reference.py."
        )
    stale_aliases = sorted(alias_names - registered)
    if stale_aliases:
        raise ReferenceGenerationError(
            f"{kind}: curated aliases that are no longer registered: {stale_aliases}."
        )
    for canonical in aliases:
        if canonical not in curated:
            raise ReferenceGenerationError(
                f"{kind}: alias group canonical name {canonical!r} has no curated description."
            )


def _iter_curated_examples() -> Iterable[Tuple[str, str]]:
    """Yield ``(origin, example_selector)`` for every curated example."""
    for kind, curated in (
        ("pseudo-classes", PSEUDO_DESCRIPTIONS),
        ("collection pseudo-classes", POST_PSEUDO_DESCRIPTIONS),
        ("relational pseudo-classes", RELATIONAL_PSEUDO_DESCRIPTIONS),
        ("parser pseudo-classes", PARSER_PSEUDO_DESCRIPTIONS),
        ("attribute operators", ATTRIBUTE_OP_DESCRIPTIONS),
        ("attribute handlers", ATTRIBUTE_HANDLER_DESCRIPTIONS),
    ):
        for name, (_desc, example) in curated.items():
            yield f"{kind} {name!r}", example
    yield "attribute operators '(bare)'", ATTRIBUTE_EXISTS_ROW[3]


def _validate_curated_examples() -> None:
    """Every example selector on the generated page must actually parse.

    Guards against documenting syntax the parser rejects (e.g. `text[size~=12]`:
    numeric ``~=`` raises at parse time by design).
    """
    from natural_pdf.selectors.parser import parse_selector

    failures: List[str] = []
    for origin, example in _iter_curated_examples():
        try:
            parse_selector(example)
        except Exception as exc:
            failures.append(f"  {origin}: {example!r} -> {exc}")
    if failures:
        raise ReferenceGenerationError(
            "curated example selectors failed to parse:\n"
            + "\n".join(failures)
            + "\nFix the examples in scripts/generate_reference.py."
        )


