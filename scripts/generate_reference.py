class ReferenceGenerationError(RuntimeError):
    """Raised when introspection and the curated maps disagree."""


# ---------------------------------------------------------------------------
# Markdown helpers
# ---------------------------------------------------------------------------


def _md_escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _md_table(headers: Sequence[str], rows: Iterable[Sequence[str]]) -> str:
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(_md_escape(cell) for cell in row) + " |")
    return "\n".join(lines)


def _page(title: str, intro: str, body: str) -> str:
    parts = [HEADER_COMMENT, "", f"# {title}", ""]
    if intro:
        parts.extend([intro.strip(), ""])
    parts.append(body.strip())
    return "\n".join(parts) + "\n"


def _code(text: str) -> str:
    return f"`{text}`"


