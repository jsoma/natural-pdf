def generate_selectors_page() -> str:
    import natural_pdf.selectors  # noqa: F401  (registers built-in clauses)
    from natural_pdf.selectors import parser as selector_parser
    from natural_pdf.selectors import registry as selector_registry

    pseudo_names = set(selector_registry._PSEUDO_HANDLERS)
    post_names = set(selector_registry._POST_HANDLERS)
    relational_names = set(selector_registry._RELATIONAL_HANDLERS)
    attribute_handler_names = set(selector_registry._ATTRIBUTE_HANDLERS)
    parser_pseudo_names = set(selector_parser._PSEUDO_CLASS_BUILDERS)
    attribute_ops = set(selector_parser._ATTRIBUTE_OP_BUILDERS)

    _guard_registry_coverage(pseudo_names, PSEUDO_DESCRIPTIONS, PSEUDO_ALIASES, "pseudo-classes")
    _guard_registry_coverage(post_names, POST_PSEUDO_DESCRIPTIONS, {}, "collection pseudo-classes")
    _guard_registry_coverage(
        relational_names, RELATIONAL_PSEUDO_DESCRIPTIONS, {}, "relational pseudo-classes"
    )
    _guard_registry_coverage(
        parser_pseudo_names, PARSER_PSEUDO_DESCRIPTIONS, {}, "parser pseudo-classes"
    )
    _guard_registry_coverage(attribute_ops, ATTRIBUTE_OP_DESCRIPTIONS, {}, "attribute operators")
    _guard_registry_coverage(
        attribute_handler_names, ATTRIBUTE_HANDLER_DESCRIPTIONS, {}, "attribute handlers"
    )
    _validate_curated_examples()

    def pseudo_rows(curated: Mapping[str, Tuple[str, str]]) -> List[Tuple[str, str, str, str]]:
        rows = []
        for name in sorted(curated):
            desc, example = curated[name]
            aliases = ", ".join(_code(f":{a}") for a in PSEUDO_ALIASES.get(name, ()))
            rows.append((_code(f":{name}"), aliases, desc, _code(example)))
        return rows

    sections: List[str] = []

    sections.append("## Pseudo-classes (element filters)")
    sections.append("Applied with a colon, e.g. `text:bold`. These filter individual elements.")
    sections.append(
        _md_table(
            ["Name", "Aliases", "What it matches", "Example"], pseudo_rows(PSEUDO_DESCRIPTIONS)
        )
    )

    sections.append("## Collection pseudo-classes")
    sections.append(
        "Applied after element filtering; they operate on the whole result list "
        "(in document order)."
    )
    sections.append(
        _md_table(
            ["Name", "Aliases", "What it does", "Example"],
            pseudo_rows(POST_PSEUDO_DESCRIPTIONS),
        )
    )

    sections.append("## Relational pseudo-classes")
    sections.append(
        "Take a reference selector as an argument and keep elements positioned "
        "relative to its first match."
    )
    sections.append(
        _md_table(
            ["Name", "Aliases", "What it does", "Example"],
            pseudo_rows(RELATIONAL_PSEUDO_DESCRIPTIONS),
        )
    )

    sections.append("## Parser-level pseudo-classes")
    sections.append(
        "Handled by the selector parser/executor itself rather than the clause registry."
    )
    sections.append(
        _md_table(
            ["Name", "Aliases", "What it does", "Example"],
            pseudo_rows(PARSER_PSEUDO_DESCRIPTIONS),
        )
    )

    sections.append("## Attribute operators")
    sections.append(
        "Applied in brackets, e.g. `text[size>12]`. Attribute names use CSS-style "
        "hyphens or Python-style underscores interchangeably."
    )
    op_rows: List[Tuple[str, str, str, str]] = [
        (
            ATTRIBUTE_EXISTS_ROW[0],
            ATTRIBUTE_EXISTS_ROW[1],
            ATTRIBUTE_EXISTS_ROW[2],
            _code(ATTRIBUTE_EXISTS_ROW[3]),
        )
    ]
    for op in sorted(ATTRIBUTE_OP_DESCRIPTIONS):
        desc, example = ATTRIBUTE_OP_DESCRIPTIONS[op]
        op_rows.append((_code(op), "", desc, _code(example)))
    sections.append(_md_table(["Operator", "Aliases", "Meaning", "Example"], op_rows))

    if attribute_handler_names:
        sections.append("## Registered attribute handlers")
        handler_rows = []
        for name in sorted(ATTRIBUTE_HANDLER_DESCRIPTIONS):
            desc, example = ATTRIBUTE_HANDLER_DESCRIPTIONS[name]
            handler_rows.append((_code(name), "", desc, _code(example)))
        sections.append(_md_table(["Name", "Aliases", "What it does", "Example"], handler_rows))

    sections.append("## Extending the vocabulary")
    sections.append(
        "Third-party packages can add clauses with `natural_pdf.selectors.register_pseudo`, "
        "`register_attribute`, `register_post_pseudo`, and `register_relational_pseudo`."
    )

    intro = (
        "Every pseudo-class and attribute operator registered in the selector engine. "
        "Generated from `natural_pdf/selectors/registry.py`, "
        "`natural_pdf/selectors/_clauses.py`, and the parser dispatch tables in "
        "`natural_pdf/selectors/parser.py`."
    )
    return _page("Selector Reference", intro, "\n\n".join(sections))


