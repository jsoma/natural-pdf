def _collect_field_docs(module: Any) -> Tuple[Dict[str, Dict[str, str]], Dict[str, Dict[str, str]]]:
    """Extract per-field descriptions and annotation text from a module via ast.

    For each dataclass field, prefer the PEP 258-style attribute docstring (a
    string literal directly after the assignment); fall back to a trailing
    ``#`` comment on the same source line. Missing descriptions are omitted.
    Returns ``(docs, annotations)``, both keyed by class name then field name.
    """
    source = inspect.getsource(module)
    source_lines = source.splitlines()
    tree = ast.parse(source)

    docs: Dict[str, Dict[str, str]] = {}
    annotations: Dict[str, Dict[str, str]] = {}
    for node in tree.body:
        if not isinstance(node, ast.ClassDef):
            continue
        class_docs: Dict[str, str] = {}
        class_annotations: Dict[str, str] = {}
        body = node.body
        for index, stmt in enumerate(body):
            if not isinstance(stmt, ast.AnnAssign) or not isinstance(stmt.target, ast.Name):
                continue
            field_name = stmt.target.id
            class_annotations[field_name] = ast.unparse(stmt.annotation)
            description = ""
            # Attribute docstring: string literal expression right after the field.
            if index + 1 < len(body):
                nxt = body[index + 1]
                if (
                    isinstance(nxt, ast.Expr)
                    and isinstance(nxt.value, ast.Constant)
                    and isinstance(nxt.value.value, str)
                ):
                    description = " ".join(nxt.value.value.split())
            if not description:
                # Trailing comment on the same line.
                line = source_lines[stmt.lineno - 1]
                if "#" in line:
                    description = line.split("#", 1)[1].strip()
            if description:
                class_docs[field_name] = description
        docs[node.name] = class_docs
        annotations[node.name] = class_annotations
    return docs, annotations


def generate_ocr_options_page() -> str:
    from natural_pdf.ocr import ocr_options as options_module
    from natural_pdf.ocr import unified_dispatch

    base = options_module.BaseOCROptions
    classes = [
        obj
        for obj in vars(options_module).values()
        if inspect.isclass(obj)
        and issubclass(obj, base)
        and obj.__module__ == options_module.__name__
        and dataclasses.is_dataclass(obj)
    ]
    ordered = [base] + sorted((c for c in classes if c is not base), key=lambda c: c.__name__)

    field_docs, field_annotations = _collect_field_docs(options_module)

    engines_by_options: Dict[str, List[str]] = {}
    engines_without_options: List[str] = []
    for name, entry in sorted(unified_dispatch.list_engines().items()):
        if entry.options_class is not None:
            engines_by_options.setdefault(entry.options_class.__name__, []).append(name)
        else:
            engines_without_options.append(name)

    def default_repr(f: dataclasses.Field) -> str:
        if f.default is not dataclasses.MISSING:
            return repr(f.default)
        if f.default_factory is not dataclasses.MISSING:  # type: ignore[misc]
            try:
                return repr(f.default_factory())
            except Exception:
                return f.default_factory.__name__
        return "(required)"

    def annotation_text(cls: type, f: dataclasses.Field) -> str:
        from_source = field_annotations.get(cls.__name__, {}).get(f.name)
        if from_source:
            return from_source
        annotation = f.type
        if isinstance(annotation, str):
            return annotation
        return str(annotation).replace("typing.", "")

    sections: List[str] = []
    for cls in ordered:
        own_fields = [
            f for f in dataclasses.fields(cls) if f.name in cls.__dict__.get("__annotations__", {})
        ]
        title = f"## `{cls.__name__}`"
        if cls is base:
            title += " (shared)"
        sections.append(title)

        used_by = engines_by_options.get(cls.__name__)
        meta_lines: List[str] = []
        doc = inspect.getdoc(cls) or ""
        if doc:
            meta_lines.append(" ".join(doc.split()))
        if used_by:
            meta_lines.append("Used by engine(s): " + ", ".join(_code(n) for n in used_by) + ".")
        elif cls is base:
            meta_lines.append(
                "Fields shared by every engine's options class. `extra_args` is passed "
                "through to the underlying engine."
            )
        if meta_lines:
            sections.append("\n\n".join(meta_lines))

        if not own_fields:
            sections.append("No options beyond the shared `BaseOCROptions` fields.")
            continue

        rows = []
        for f in own_fields:
            rows.append(
                (
                    _code(f.name),
                    _code(annotation_text(cls, f)),
                    _code(default_repr(f)),
                    field_docs.get(cls.__name__, {}).get(f.name, ""),
                )
            )
        sections.append(_md_table(["Option", "Type", "Default", "Description"], rows))

    if engines_without_options:
        sections.append("## Engines without a typed options class")
        sections.append(
            ", ".join(_code(n) for n in sorted(engines_without_options))
            + " — configure these through `apply_ocr()` keyword arguments (e.g. `model=`) "
            "instead of an options dataclass."
        )

    intro = (
        "Typed option dataclasses from `natural_pdf/ocr/ocr_options.py`. Pass an "
        'instance via `page.apply_ocr(engine="...", options=...)`. Subclass tables '
        "list only the fields each class adds; every class also accepts the shared "
        "`BaseOCROptions` fields."
    )
    return _page("OCR Options Reference", intro, "\n\n".join(sections))


