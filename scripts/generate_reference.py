def generate_exceptions_page() -> str:
    import natural_pdf.exceptions as exc_module

    module_name = exc_module.__name__
    classes = {
        name: obj
        for name, obj in vars(exc_module).items()
        if inspect.isclass(obj) and issubclass(obj, BaseException) and obj.__module__ == module_name
    }

    children: Dict[str, List[str]] = {name: [] for name in classes}
    roots: List[str] = []
    for name, obj in classes.items():
        in_module_bases = [b.__name__ for b in obj.__bases__ if b.__name__ in classes]
        if in_module_bases:
            children[in_module_bases[0]].append(name)
        else:
            roots.append(name)

    def first_doc_line(obj: type) -> str:
        doc = inspect.getdoc(obj) or ""
        return doc.splitlines()[0].strip() if doc else ""

    lines: List[str] = []

    def render(name: str, depth: int) -> None:
        obj = classes[name]
        base = obj.__bases__[0].__name__
        suffix = f" — {first_doc_line(obj)}" if first_doc_line(obj) else ""
        if depth == 0:
            lines.append(f"- `{name}({base})`{suffix}")
        else:
            lines.append("    " * depth + f"- `{name}`{suffix}")
        for child in sorted(children[name]):
            render(child, depth + 1)

    for root in sorted(roots):
        render(root, 0)

    body = "\n".join(lines)
    body += (
        "\n\nCatch `NaturalPDFError` to handle every library-raised error with one "
        "handler:\n\n"
        "```python\n"
        "from natural_pdf.exceptions import NaturalPDFError\n\n"
        "try:\n"
        "    pdf.apply_ocr()\n"
        "except NaturalPDFError as e:\n"
        "    handle_error(e)\n"
        "```"
    )

    intro = (
        "The exception hierarchy defined in `natural_pdf/exceptions.py`, introspected "
        "from the module. Indentation shows inheritance."
    )
    return _page("Exception Reference", intro, body)


