def generate_installation_extras_page() -> str:
    from natural_pdf.utils import optional_imports

    deps = optional_imports.OPTIONAL_DEPENDENCIES
    groups = optional_imports.OPTIONAL_DEPENDENCY_GROUPS

    default_applicable = optional_imports.OptionalDependency.__dataclass_fields__[
        "applicable"
    ].default

    def dep_rows(names: Iterable[str]) -> List[Tuple[str, str, str, str]]:
        rows = []
        for name in names:
            dep = deps[name]
            packages = ", ".join(_code(p) for p in (dep.package_names or (dep.module_name,)))
            desc = dep.description or ""
            if dep.applicable is not default_applicable:
                desc = (
                    desc + " " if desc else ""
                ) + "(Platform-conditional: `npdf doctor` shows N/A where it does not apply.)"
            hints = " or ".join(_code(h) for h in dep.install_hints)
            rows.append((_code(name), packages, desc, hints))
        return rows

    sections: List[str] = []
    for group in sorted(groups):
        sections.append(f"## `natural-pdf[{group}]`")
        sections.append(f'Install: `pip install "natural-pdf[{group}]"`')
        sections.append(
            _md_table(
                ["Dependency", "Packages", "What it enables", "Install on its own"],
                dep_rows(groups[group]),
            )
        )

    grouped = {name for members in groups.values() for name in members}
    ungrouped = sorted(set(deps) - grouped)
    if ungrouped:
        sections.append("## Not in any extra")
        sections.append("These optional dependencies are opt-in: install them individually.")
        sections.append(
            _md_table(
                ["Dependency", "Packages", "What it enables", "Install on its own"],
                dep_rows(ungrouped),
            )
        )

    intro = (
        "The optional dependency matrix from `natural_pdf.utils.optional_imports` — "
        "the same data `npdf doctor` reports for your environment. Each extra is a "
        "pip install target; each row is one optional dependency the library probes "
        "for at runtime."
    )
    return _page("Installation Extras", intro, "\n\n".join(sections))


